const test=require('node:test');
const assert=require('node:assert/strict');
const {createCollaboration,decodeInvite,localAddress,pinnedAgent,request}=require('../desktop/collaboration.cjs');
const fixture=()=>({id:'design-1',name:'Shared launch',width:1080,height:1080,pages:[{id:'page-1',name:'Launch',data:{background:'#fff',objects:[{id:'title',type:'Textbox',text:'Hello',left:10,top:10,width:100}]},comments:[]}]});
const until=async fn=>{const end=Date.now()+10000;while(!fn()){if(Date.now()>end)throw new Error('Timed out waiting for collaboration.');await new Promise(r=>setTimeout(r,30));}};
const options={allowLoopback:true,getInterfaces:()=>[{name:'Test LAN',address:'127.0.0.1'}]};
test('invitations accept private addresses only and expire',()=>{
  for(const ip of ['10.0.0.2','172.16.1.2','192.168.0.8','100.64.0.8'])assert.equal(localAddress(ip),true);
  for(const ip of ['8.8.8.8','127.0.0.1','169.254.169.254/','192.168.999.1','localhost','example.com'])assert.equal(localAddress(ip),false);
  const info={address:'192.168.1.5',port:52123,fingerprint:'a'.repeat(64),key:'a'.repeat(43),expiresAt:Date.now()-100};
  assert.throws(()=>decodeInvite('FORMA-LAN-1.'+Buffer.from(JSON.stringify(info)).toString('base64url')),/expired/);
});
test('two encrypted native peers require approval, enforce permissions, sync changes and revoke access',async t=>{
  const {diffDesign}=await import('../shared/collaboration.mjs');
  const hostEvents=[],guestEvents=[];
  const host=await createCollaboration({...options,onEvent:event=>hostEvents.push(event)}),guest=await createCollaboration({...options,onEvent:event=>guestEvents.push(event)});
  t.after(async()=>{await guest.stop();await host.stop();});
  await host.host({name:'Host',address:'127.0.0.1',design:fixture()});
  const firstCode=host.status().invitation.code;
  const join=guest.join({name:'Reviewer',code:firstCode});
  await until(()=>host.status().pending.length===1);assert.equal(guest.status().mode,'joining');
  const id=host.status().pending[0].id;host.admit({id,allow:true,role:'comment'});
  const accepted=await join;assert.equal(accepted.state.self.role,'comment');assert.equal(accepted.design.name,'Shared launch');
  const next=fixture();next.pages[0].data.objects[0].text='Not allowed';
  await assert.rejects(()=>guest.publish({id:'forged',ops:diffDesign(fixture(),next)}),/permission/);
  const commented=fixture();commented.pages[0].comments.push({id:'comment-1',text:'Make the heading larger',x:50,y:20,resolved:false,createdAt:new Date().toISOString(),authorId:'fake'});
  await guest.publish({id:'comment-update',ops:diffDesign(fixture(),commented)});
  await until(()=>guestEvents.some(event=>event.transactionId==='comment-update'));
  const commentEvent=hostEvents.find(event=>event.transactionId==='comment-update');assert.equal(commentEvent.ops[0].after.authorId,id);
  host.permission({id,role:'edit'});await until(()=>guest.status().self.role==='edit');
  await guest.publish({id:'artwork-update',ops:diffDesign(fixture(),next)});
  await until(()=>guestEvents.some(event=>event.transactionId==='artwork-update'));
  assert.equal(hostEvents.find(event=>event.transactionId==='artwork-update').ops[0].after,'Not allowed');
  await guest.publish({id:'artwork-update',ops:diffDesign(fixture(),next)});
  assert.equal(hostEvents.filter(event=>event.transactionId==='artwork-update').length,1);
  await guest.presence({pageId:'page-1',x:100,y:120,selection:['title']});
  await until(()=>hostEvents.some(event=>event.type==='presence'&&event.participantId===id));
  host.permission({id,role:'view'});await until(()=>guest.status().self.role==='view');
  await assert.rejects(()=>guest.publish({id:'view-forgery',ops:diffDesign(fixture(),commented)}),/permission/);
  host.renew();assert.notEqual(host.status().invitation.code,firstCode);
  const old=await createCollaboration(options);await assert.rejects(()=>old.join({name:'Old invite',code:firstCode}),/invalid|expired/);await old.stop();
  host.remove(id);await until(()=>guest.status().mode==='idle');assert.ok(guestEvents.some(event=>event.type==='ended'));
});
test('wrong certificate pins fail before admission, and the service exposes no editor or AI routes',async t=>{
  const host=await createCollaboration(options);t.after(()=>host.stop());await host.host({name:'Host',address:'127.0.0.1',design:fixture()});
  const code=host.status().invitation.code,info=decodeInvite(code,true),agent=pinnedAgent(info);t.after(()=>agent.destroy());
  await assert.rejects(()=>request(info,agent,'/desktop/capture',{}),/Not found/);
  const bad={...info,fingerprint:'0'.repeat(64)},guest=await createCollaboration(options);t.after(()=>guest.stop());
  await assert.rejects(()=>guest.join({name:'Wrong certificate',code:'FORMA-LAN-1.'+Buffer.from(JSON.stringify(bad)).toString('base64url')}),/certificate/);
  assert.equal(host.status().pending.length,0);
});
